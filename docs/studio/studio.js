/** @type {Array<{el: HTMLElement, blob: Blob|null, buffer: AudioBuffer|null}>} */
const takes = [];
let audioContext = null;

/** The pronunciation the stage edits. Only meaningful when there is more than one. */
let activeTake = null;

function setActive(take) {
  activeTake = take;
  for (const other of takes) {
    const picked = other === take;
    other.el.classList.toggle('is-active', picked);
    other.el.querySelector('.pick').setAttribute('aria-pressed', String(picked));
  }
  refresh();
}

function ctx() {
  audioContext ??= new (window.AudioContext ?? window.webkitAudioContext)();
  return audioContext;
}

function slug(text) {
  return (
    text
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'name'
  );
}

function fileNameFor(take, index) {
  const lang = take.el.querySelector('.in-lang').value.trim();
  const suffix = lang ? `-${slug(lang)}` : takes.length > 1 ? `-${index + 1}` : '';
  return `${slug(nameInput.value)}${suffix}.wav`;
}

function fields(take) {
  const get = (cls) => take.el.querySelector(cls).value.trim();
  return {
    label: get('.in-label'),
    lang: get('.in-lang'),
    respell: get('.in-respell'),
    ipa: get('.in-ipa'),
    trim: take.el.querySelector('.in-trim').checked,
    synthetic: take.el.querySelector('.in-synthetic').checked,
  };
}

/** How long to wait after the last keystroke before re-deriving. */
const AUTO_DELAY_MS = 500;

/**
 * Whether this visitor has already accepted the engine download.
 *
 * Stored per-browser so the choice survives a reload: having paid the 9 MB once, they get
 * automatic filling from the first keystroke on every later visit. Wrapped because private
 * windows and blocked site data make localStorage throw rather than return null.
 */
const OPT_IN_KEY = 'say-my-name:espeak-opt-in';

function hasOptedIn() {
  try {
    return localStorage.getItem(OPT_IN_KEY) === 'yes';
  } catch {
    return false;
  }
}

function rememberOptIn() {
  try {
    localStorage.setItem(OPT_IN_KEY, 'yes');
  } catch {
    // No storage available; this visit still works, the next one just asks again.
  }
}

/**
 * Re-derive the IPA and respelling from the current name and language.
 *
 * Runs as you type. The first one fetches eSpeak (~9 MB) and says so while it does;
 * afterwards each derivation is a ~250 ms local call.
 *
 * Leaves the audio alone unless eSpeak generated it. A recording or an uploaded file is
 * something the author chose, and changing a language tag is not permission to discard it.
 */
async function autoDerive(take) {
  const ipaField = take.el.querySelector('.in-ipa');
  if (ipaField.dataset.edited === 'true') return;

  const name = nameInput.value.trim();
  if (!name) return;

  // First derivation of the visit pays for the engine. Say so rather than appearing to
  // hang: 9 MB takes a moment, and silence looks like nothing happened.
  if (!engineRequested()) {
    take.el.querySelector('.rec-status').textContent =
      `Fetching the speech engine (~${ENGINE_MB} MB, once per visit)…`;
    markAutoMode();
    rememberOptIn();
  }

  try {
    const { ipa, wav } = await suggest(name, fields(take).lang);
    ipaField.value = ipa;
    syncRespelling(take);

    if (take.generated) {
      take.blob = wav;
      take.buffer = await ctx().decodeAudioData(await wav.arrayBuffer());
      takeReady(take, 'Regenerated by eSpeak — a guess. Edit the IPA, or record it yourself.');
      return;
    }
    take.el.querySelector('.rec-status').textContent = take.blob
      ? take.el.querySelector('.rec-status').textContent
      : 'Filled from the spelling. Press Speak it to hear it, or record your own.';
    refresh();
  } catch (error) {
    console.warn('<say-my-name> studio: could not re-derive.', error);
    take.el.querySelector('.rec-status').textContent =
      'Could not work that out. Check the language tag, e.g. pt-BR.';
  }
}

/** Coalesce keystrokes so a five-letter name is one derivation, not five. */
function scheduleAutoDerive(take) {
  clearTimeout(take.timer);
  take.timer = setTimeout(() => void autoDerive(take), AUTO_DELAY_MS);
}

/**
 * Keep the respelling in step with the IPA.
 *
 * Runs on every IPA change — typed, pasted or generated — because the conversion is a pure
 * string function with no engine behind it. Stops the moment the author edits the
 * respelling themselves: a suggestion should never overwrite a considered choice.
 */
function syncRespelling(take) {
  const respellField = take.el.querySelector('.in-respell');
  if (respellField.dataset.edited === 'true') return;

  const suggestion = respellFromIpa(take.el.querySelector('.in-ipa').value);
  if (suggestion) respellField.value = suggestion;
}

/** The trimmed mono samples for a take, or null if nothing has been recorded yet. */
function samplesFor(take) {
  if (!take.buffer) return null;
  const all = toMono(take.buffer);
  if (!fields(take).trim) return all;
  const { start, end } = findSpeechBounds(all, take.buffer.sampleRate);
  return all.subarray(start, end);
}

function drawWave(take) {
  const canvas = take.el.querySelector('.wave');
  const context = canvas.getContext('2d');
  const width = canvas.width;
  const height = canvas.height;
  context.clearRect(0, 0, width, height);

  const samples = samplesFor(take);
  canvas.hidden = !samples?.length;
  if (!samples?.length) return;

  const styles = getComputedStyle(document.body);
  context.fillStyle = styles.getPropertyValue('--accent').trim() || '#7b4bd8';

  const peaks = envelope(samples, Math.floor(width / 3));
  peaks.forEach((peak, i) => {
    const barHeight = Math.max(2, peak * height * 0.9);
    context.fillRect(i * 3, (height - barHeight) / 2, 2, barHeight);
  });
}

function humanSize(bytes) {
  return bytes > 1024 * 1024
    ? `${(bytes / 1024 / 1024).toFixed(1)} MB`
    : `${Math.round(bytes / 1024)} KB`;
}

function updateSizes(take) {
  const samples = samplesFor(take);
  const sizeEl = take.el.querySelector('.size');
  if (!samples || !take.blob) {
    sizeEl.textContent = '';
    return;
  }
  const seconds = samples.length / take.buffer.sampleRate;
  sizeEl.textContent =
    `${seconds.toFixed(1)}s · wav ${humanSize(44 + samples.length * 2)} · ` +
    `original ${humanSize(take.blob.size)}`;
}

/** Extension for the untouched take: the real one if we were handed a file, else by type. */
function rawExtension(blob) {
  if (blob.name?.includes('.')) return blob.name.split('.').pop().toLowerCase();
  const type = blob.type ?? '';
  if (/mp4|m4a|aac/.test(type)) return 'm4a';
  if (/mpeg|mp3/.test(type)) return 'mp3';
  if (/ogg|opus/.test(type)) return 'opus';
  if (/wav/.test(type)) return 'wav';
  return 'webm';
}

function download(blob, filename) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.click();
  // Revoked on the next tick so the download has already started.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

async function record(take) {
  const button = take.el.querySelector('.record');
  const status = take.el.querySelector('.rec-status');

  let stream;
  try {
    stream = await navigator.mediaDevices.getUserMedia({ audio: true });
  } catch {
    status.textContent = 'Microphone permission denied.';
    return;
  }

  const recorder = new MediaRecorder(stream);
  const chunks = [];
  recorder.addEventListener('dataavailable', (event) => chunks.push(event.data));

  recorder.addEventListener('stop', async () => {
    for (const track of stream.getTracks()) track.stop();
    button.textContent = '● Re-record';
    button.classList.remove('recording');

    take.blob = new Blob(chunks, { type: recorder.mimeType });
    try {
      take.buffer = await ctx().decodeAudioData(await take.blob.arrayBuffer());
    } catch {
      status.textContent = 'Could not decode that recording — try again.';
      return;
    }

    take.generated = false;
    takeReady(take, 'Recorded');
  });

  recorder.start();
  button.textContent = '■ Stop';
  button.classList.add('recording');
  status.textContent = 'Recording — say your name, then press stop';

  const stop = () => {
    if (recorder.state !== 'inactive') recorder.stop();
    button.removeEventListener('click', stop);
  };
  button.addEventListener('click', stop);

  // A name takes a second; this is a backstop against a forgotten open microphone.
  setTimeout(stop, 15000);
}

/** Enable everything that only makes sense once a take has audio in it. */
function takeReady(take, statusText) {
  take.el.querySelector('.rec-status').textContent = statusText;
  take.el.querySelector('.play').disabled = false;
  take.el.querySelector('.dl-wav').disabled = false;
  take.el.querySelector('.dl-raw').disabled = false;
  drawWave(take);
  updateSizes(take);
  refresh();
}

/**
 * Load an audio file the user made elsewhere — a TTS site, a phone memo, anything.
 *
 * decodeAudioData runs locally on an ArrayBuffer; the file is never sent anywhere, same
 * as a recording made here.
 */
async function loadFile(take, file) {
  clearTimeout(take.timer);
  const status = take.el.querySelector('.rec-status');
  status.textContent = `Reading ${file.name}…`;
  try {
    const buffer = await ctx().decodeAudioData(await file.arrayBuffer());
    take.blob = file;
    take.buffer = buffer;
  } catch {
    status.textContent = 'Could not decode that file. Try .wav, .mp3, .m4a, .ogg or .opus.';
    return;
  }
  take.el.querySelector('.record').textContent = '● Record instead';
  take.generated = false;
  takeReady(take, `Loaded ${file.name}`);
}

/**
 * Fill in a pronunciation from the spelling, using eSpeak's letter-to-sound rules.
 *
 * Deliberately suggests rather than decides: rule-based conversion gets names of foreign
 * origin wrong routinely, so everything it writes stays editable, and the result is marked
 * synthesized so it can never be mistaken for the owner's voice.
 */
async function suggestFor(take) {
  const status = take.el.querySelector('.rec-status');
  const button = take.el.querySelector('.suggest');
  const name = nameInput.value.trim();

  if (!name) {
    status.textContent = 'Type a name first.';
    return;
  }

  // A pending auto-derive would redo this work a moment later and overwrite the status.
  clearTimeout(take.timer);

  button.disabled = true;
  status.textContent = engineRequested()
    ? 'Generating…'
    : `Fetching the speech engine (~${ENGINE_MB} MB, once per visit)…`;

  try {
    const { ipa, wav } = await suggest(name, fields(take).lang);
    take.el.querySelector('.in-ipa').value = ipa;
    syncRespelling(take);
    // Non-negotiable: a generated voice is always marked as one.
    take.el.querySelector('.in-synthetic').checked = true;
    take.blob = wav;
    take.buffer = await ctx().decodeAudioData(await wav.arrayBuffer());
    take.el.querySelector('.record').textContent = '● Record instead';
    take.generated = true;
    rememberOptIn();
    markAutoMode();
    takeReady(take, 'Generated by eSpeak — a guess. Edit the IPA, or record it yourself.');
  } catch (error) {
    console.warn('<say-my-name> studio: eSpeak failed.', error);
    status.textContent = 'Could not generate that. Check the language tag, e.g. pt-BR.';
  } finally {
    button.disabled = false;
  }
}

/**
 * Which editable value a click inside the component landed on.
 *
 * The component exposes its internals through `part`, and clicks cross the shadow boundary
 * in composedPath, so the rendered output can be treated as the editing surface without
 * the studio knowing anything about its internal markup.
 */
const EDITABLE_PARTS = {
  name: { field: null, label: 'name' },
  respell: { field: '.in-respell', label: 'respelling' },
  ipa: { field: '.in-ipa', label: 'IPA' },
};

function editableFrom(event) {
  for (const node of event.composedPath()) {
    const part = node?.getAttribute?.('part');
    if (!part) continue;
    for (const token of part.split(/\s+/)) {
      if (EDITABLE_PARTS[token]) return { token, node, ...EDITABLE_PARTS[token] };
    }
  }
  return null;
}

/**
 * Put an input exactly where the text sits, matching its size and font.
 *
 * This is what makes the page feel like the artifact rather than a form about it: you
 * click the thing you want to change and type over it.
 */
/** Breathing room between the editor and the window edge. */
const EDGE_PAD = 8;

function clamp(value, low, high) {
  return Math.min(Math.max(value, low), Math.max(low, high));
}

function editInPlace(target) {
  const { node, field, label } = target;
  const take = activeTake ?? takes[0];
  const source = field ? take.el.querySelector(field) : nameInput;

  const rect = node.getBoundingClientRect();
  const style = getComputedStyle(node);

  // The editor is absolutely positioned on the body, so its width has to be stated and
  // kept inside the viewport. Left to a percentage — which the page's own input rule
  // would otherwise give it — a full-width box anchored at the name's left edge widens
  // the document and shunts the whole layout sideways.
  const page = document.documentElement.clientWidth;
  const width = Math.min(Math.max(rect.width + 24, 90), page - 2 * EDGE_PAD);
  const left = clamp(rect.left, EDGE_PAD, page - width - EDGE_PAD);

  const input = document.createElement('input');
  input.type = 'text';
  input.className = 'inline-edit';
  input.value = source.value;
  input.setAttribute('aria-label', `Edit ${label}`);
  Object.assign(input.style, {
    left: `${left + window.scrollX}px`,
    top: `${rect.top + window.scrollY}px`,
    height: `${Math.max(rect.height, 24)}px`,
    width: `${width}px`,
    font: style.font,
    letterSpacing: style.letterSpacing,
  });

  // Enter commits and closes, which then fires blur — so closing has to be idempotent
  // or the second pass throws on an already-detached node.
  let closed = false;
  const close = (keep) => {
    if (closed) return;
    closed = true;
    if (keep && source.value !== input.value) {
      source.value = input.value;
      source.dispatchEvent(new Event('input', { bubbles: true }));
    }
    input.remove();
  };

  input.addEventListener('blur', () => close(true));
  input.addEventListener('keydown', (event) => {
    if (event.key === 'Enter') close(true);
    if (event.key === 'Escape') close(false);
  });

  document.body.append(input);
  input.focus();
  input.select();
}

/** Once the engine is loaded the note about downloading it is just noise. */
function markAutoMode() {
  document.body.dataset.espeak = 'ready';
}

function playTake(take) {
  const samples = samplesFor(take);
  if (!samples) return;
  const buffer = ctx().createBuffer(1, samples.length, take.buffer.sampleRate);
  buffer.copyToChannel(samples, 0);
  const source = ctx().createBufferSource();
  source.buffer = buffer;
  source.connect(ctx().destination);
  source.start();
}

function addTake() {
  const fragment = template.content.cloneNode(true);
  const el = fragment.querySelector('.take');
  const take = { el, blob: null, buffer: null, generated: false, timer: 0 };
  takes.push(take);
  takesEl.append(el);

  el.querySelector('.record').addEventListener('click', () => {
    if (!el.querySelector('.record').classList.contains('recording')) void record(take);
  });
  el.querySelector('.play').addEventListener('click', () => playTake(take));
  el.querySelector('.pick').addEventListener('click', () => setActive(take));
  el.addEventListener('focusin', () => setActive(take));
  el.querySelector('.suggest').addEventListener('click', () => void suggestFor(take));
  el.querySelector('.in-file').addEventListener('change', (event) => {
    const [file] = event.target.files ?? [];
    if (file) void loadFile(take, file);
  });
  el.querySelector('.remove').addEventListener('click', () => {
    takes.splice(takes.indexOf(take), 1);
    el.remove();
    refresh();
  });
  el.querySelector('.in-trim').addEventListener('change', () => {
    drawWave(take);
    updateSizes(take);
  });
  el.querySelector('.dl-wav').addEventListener('click', () => {
    const samples = samplesFor(take);
    if (samples) download(encodeWav(samples, take.buffer.sampleRate), fileNameFor(take, takes.indexOf(take)));
  });
  el.querySelector('.dl-raw').addEventListener('click', () => {
    if (!take.blob) return;
    const ext = rawExtension(take.blob);
    download(take.blob, fileNameFor(take, takes.indexOf(take)).replace(/\.wav$/, `.${ext}`));
  });

  el.querySelector('.in-ipa').addEventListener('input', (event) => {
    // Hand-written IPA is never overwritten by a later derivation.
    event.target.dataset.edited = 'true';
    syncRespelling(take);
    refresh();
  });
  el.querySelector('.in-lang').addEventListener('input', () => scheduleAutoDerive(take));
  el.querySelector('.in-lang').addEventListener('change', () => scheduleAutoDerive(take));
  // Typing here hands control to the author for good.
  el.querySelector('.in-respell').addEventListener('input', (event) => {
    event.target.dataset.edited = 'true';
  });

  for (const input of el.querySelectorAll('input')) {
    input.addEventListener('input', refresh);
  }

  refresh();
}

/** Blob URLs handed to the preview, revoked on the next render so they don't pile up. */
let previewUrls = [];

/** Build the live preview out of the real component, fed by blob URLs. */
function renderPreview() {
  const name = nameInput.value.trim() || 'Your name';
  previewEl.replaceChildren();
  // refresh() runs on every keystroke; without this, each one leaks an encoded WAV.
  for (const url of previewUrls) URL.revokeObjectURL(url);
  previewUrls = [];

  const element = document.createElement('say-my-name');
  element.setAttribute('display', displaySelect.value);
  if (showSelect.value !== 'both') element.setAttribute('show', showSelect.value);
  element.append(document.createTextNode(name));

  const list = takes.map((take) => {
    const { label, lang, respell, ipa, synthetic } = fields(take);
    const entry = {};
    if (label) entry.label = label;
    if (lang) entry.lang = lang;
    if (respell) entry.respell = respell;
    if (ipa) entry.ipa = ipa;
    if (synthetic) entry.synthetic = true;
    const samples = samplesFor(take);
    if (samples) {
      const url = URL.createObjectURL(encodeWav(samples, take.buffer.sampleRate));
      previewUrls.push(url);
      entry.audio = url;
    }
    return entry;
  });

  if (list.length === 1) {
    for (const [key, value] of Object.entries(list[0])) {
      element.setAttribute(key === 'ttsText' ? 'tts-text' : key, value);
    }
  } else if (list.length > 1) {
    const script = document.createElement('script');
    script.type = 'application/json';
    script.textContent = JSON.stringify(list);
    element.append(script);
  }

  previewEl.append(element);
  syncGhostEdits(element);
}

/**
 * Show a way in for anything the widget is not currently displaying.
 *
 * The stage is the editing surface, which only works for what is on it: an empty IPA has
 * nothing to click, and `display="none"` hides both written forms by design. Rather than
 * put the fields back on the page permanently, they appear only while they are unreachable.
 */
function syncGhostEdits(element) {
  const take = activeTake ?? takes[0];
  for (const button of document.querySelectorAll('.ghost-edit')) {
    const { field, label } = EDITABLE_PARTS[button.dataset.edit];
    const value = take ? take.el.querySelector(field).value.trim() : '';
    const onStage = Boolean(
      element.shadowRoot?.querySelector(`[part~="${button.dataset.edit}"]`),
    );
    button.hidden = Boolean(value) && onStage;
    button.textContent = value ? `${label}: ${value}` : `+ add ${label}`;
  }
}

/** The snippet the user pastes into their own site. */
function renderSnippet() {
  const name = nameInput.value.trim() || 'Your name';
  const base = pathInput.value.trim().replace(/\/?$/, '/');
  const display = displaySelect.value;
  const shown = showSelect.value;

  const entries = takes.map((take, index) => {
    const { label, lang, respell, ipa, synthetic } = fields(take);
    const entry = {};
    if (label) entry.label = label;
    if (lang) entry.lang = lang;
    if (take.buffer) entry.audio = base + fileNameFor(take, index);
    if (respell && shown !== 'ipa') entry.respell = respell;
    if (ipa && shown !== 'respell') entry.ipa = ipa;
    if (synthetic) entry.synthetic = true;
    return entry;
  });

  const attrs = [];
  if (display !== 'inline') attrs.push(`display="${display}"`);
  if (showSelect.value !== 'both') attrs.push(`show="${showSelect.value}"`);

  if (entries.length <= 1) {
    const entry = entries[0] ?? {};
    for (const key of ['audio', 'respell', 'ipa', 'lang']) {
      if (entry[key]) attrs.push(`${key}="${escapeAttr(entry[key])}"`);
    }
    if (entry.synthetic) attrs.push('synthetic');
    const open = attrs.length ? `<say-my-name ${attrs.join(' ')}>` : '<say-my-name>';
    snippetEl.textContent = `${open}${name}</say-my-name>`;
    return;
  }

  const json = JSON.stringify(entries, null, 2)
    .split('\n')
    .map((line) => `    ${line}`)
    .join('\n');

  snippetEl.textContent =
    `<say-my-name${attrs.length ? ` ${attrs.join(' ')}` : ''}>\n` +
    `  ${name}\n` +
    `  <script type="application/json">\n${json}\n  </` +
    `script>\n` +
    `</say-my-name>`;
}

function escapeAttr(value) {
  return value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

function refresh() {
  for (const [index, take] of takes.entries()) {
    const named = fields(take).label;
    take.el.querySelector('.pick-label').textContent =
      named || (takes.length > 1 ? `Pronunciation ${index + 1}` : 'Pronunciation');
    take.el.querySelector('.remove').hidden = takes.length < 2;
  }
  renderPreview();
  renderSnippet();
}

document.querySelector('#add-take').addEventListener('click', addTake);
nameInput.addEventListener('input', () => {
  refresh();
  for (const take of takes) scheduleAutoDerive(take);
});
pathInput.addEventListener('input', refresh);
displaySelect.addEventListener('change', refresh);
showSelect.addEventListener('change', refresh);

document.querySelector('#copy').addEventListener('click', async () => {
  const status = document.querySelector('#copy-status');
  try {
    await navigator.clipboard.writeText(snippetEl.textContent);
    status.textContent = 'Copied.';
  } catch {
    status.textContent = 'Copy failed — select the snippet and copy it manually.';
  }
  setTimeout(() => (status.textContent = ''), 3000);
});

if (!navigator.mediaDevices?.getUserMedia) {
  document.querySelector('#takes').insertAdjacentHTML(
    'beforebegin',
    '<p class="warn">This browser has no microphone access — but you can still use an ' +
      'audio file, fill in the phonetic fields, and copy the snippet.</p>',
  );
}

/** One shared datalist for every take: 133 languages is too many to duplicate per card. */
function fillLanguageList() {
  const list = document.querySelector('#languages');
  if (!list) return;
  list.replaceChildren(
    ...VOICES.map(({ code, name }) => {
      const option = document.createElement('option');
      option.value = code;
      option.label = `${name} — ${code}`;
      return option;
    }),
  );
}

fillLanguageList();

// The rendered component is the editing surface.
previewEl.addEventListener('click', (event) => {
  const target = editableFrom(event);
  // Let the play button be a play button.
  if (!target || event.composedPath().some((n) => n?.tagName === 'BUTTON')) return;
  event.preventDefault();
  editInPlace(target);
});

